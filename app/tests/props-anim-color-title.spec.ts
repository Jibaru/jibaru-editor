import { expect, test, boot, choose, clipOf, effect, menuItem, module, openModule, pval, row, selectClip, setModule, setRow } from './helpers'
import { fixture } from './paths'

const S = 10_000_000

test('animation: in/out presets in the animation slots, duration, none, filter', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.video, 'Animation')
  await page.locator('[data-anim="jb.anim.zoom_in"]').click()
  let c = await clipOf(page, b.clips.video)
  expect(c.animations).toHaveLength(1)
  expect(c.animations[0]).toMatchObject({ kind: 'jb.anim.zoom_in', placement: 'in' })
  await setRow(page, page.locator('.properties'), 'Duration', 1.5)
  c = await clipOf(page, b.clips.video)
  expect(c.animations[0].range).toEqual([0, 1.5 * S])
  await page.locator('.pills.inout button', { hasText: 'Out' }).click()
  await page.locator('[data-anim="jb.anim.fade_out"]').click()
  c = await clipOf(page, b.clips.video)
  expect(c.animations.map((a: any) => a.placement).sort()).toEqual(['in', 'out'])
  await page.locator('.preset', { hasText: 'No Motion' }).click()
  c = await clipOf(page, b.clips.video)
  expect(c.animations.map((a: any) => a.placement)).toEqual(['in'])
  await page.locator('.anim-head button[title="Filter"]').click()
  await menuItem(page, /^Slide$/)
  await expect(page.locator('[data-anim]').first()).toHaveAttribute('data-anim', /slide/)
})

test('keyframe presets write keyframes over the clip', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.video, 'Animation')
  await page.locator('.sub-tabs button', { hasText: 'Keyframe Presets' }).click()
  await page.locator('[data-kfpreset="zoom_in"]').click()
  let c = await clipOf(page, b.clips.video)
  expect(c.transform.scale_x.keyframes.map((k: any) => [k.time, k.value.value])).toEqual([
    [0, 1],
    [4 * S, 1.3],
  ])
  await page.locator('[data-kfpreset="pan_left"]').click()
  c = await clipOf(page, b.clips.video)
  expect(c.transform.position_x.keyframes).toHaveLength(2)
  await page.locator('.preset', { hasText: 'None' }).click()
  c = await clipOf(page, b.clips.video)
  expect(c.transform.position_x.keyframes ?? []).toHaveLength(0)
  expect(c.transform.scale_x.keyframes ?? []).toHaveLength(0)
})

test('color basic: presets, sliders, auto white balance, save and apply custom preset', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.video, 'Color')
  await page.locator('[data-preset="Boost Color"]').click()
  let e = effect(await clipOf(page, b.clips.video), 'jb.color.adjust')
  expect([pval(e, 'saturation'), pval(e, 'vibrance')]).toEqual([60, 30])
  await page.locator('.expand-bar').click()
  await expect(page.locator('[data-preset="Black & White"]')).toHaveCount(1)
  await setRow(page, module(page, 'Light'), 'Exposure', 20)
  e = effect(await clipOf(page, b.clips.video), 'jb.color.adjust')
  expect(pval(e, 'exposure')).toBe(20)
  await setModule(page, 'Light', false)
  expect(pval(effect(await clipOf(page, b.clips.video), 'jb.color.adjust'), 'exposure')).toBe(0)
  await setModule(page, 'Light', true)
  expect(pval(effect(await clipOf(page, b.clips.video), 'jb.color.adjust'), 'exposure')).toBe(20)
  await row(page, module(page, 'Color'), 'Auto White Balance').locator('button', { hasText: 'Auto' }).click()
  await expect.poll(async () => typeof pval(effect(await clipOf(page, b.clips.video), 'jb.color.adjust'), 'temperature')).toBe('number')
  // Save as Custom, then apply it to another clip.
  await page.locator('.prop-footer button', { hasText: 'Save as Custom' }).click()
  await page.locator('.save-preset input').fill('My Look')
  await page.locator('.save-preset button', { hasText: 'Save' }).click()
  await selectClip(page, b.clips.after, 'Color')
  await page.locator('.pills.wide-pills button', { hasText: 'Custom' }).click()
  await page.locator('[data-preset="My Look"]').click()
  e = effect(await clipOf(page, b.clips.after), 'jb.color.adjust')
  expect(pval(e, 'exposure')).toBe(20)
  // Compare turns the adjustments off and back on.
  await page.locator('.sub-compare').click()
  expect(effect(await clipOf(page, b.clips.after), 'jb.color.adjust').enabled).toBe(false)
  await page.locator('.sub-compare').click()
  expect(effect(await clipOf(page, b.clips.after), 'jb.color.adjust').enabled).toBe(true)
  await page.locator('.prop-footer button', { hasText: 'Reset' }).click()
  expect(effect(await clipOf(page, b.clips.after), 'jb.color.adjust')).toBeUndefined()
})

