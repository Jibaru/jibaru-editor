test('HSL, curves and color wheels', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.video, 'Color')
  await page.locator('.sub-tabs button', { hasText: 'HSL' }).click()
  await page.locator('.hsl-dot[data-hsl="blue"]').click()
  await setRow(page, module(page, 'HSL'), 'Saturation', -40)
  expect(pval(effect(await clipOf(page, b.clips.video), 'jb.color.hsl'), 'blue_sat')).toBe(-40)
  await page.locator('.sub-tabs button', { hasText: 'Curves' }).click()
  await page.locator('.pills button', { hasText: 'Red' }).click()
  const svg = page.locator('.curve-svg')
  const box = (await svg.boundingBox())!
  await page.mouse.dblclick(box.x + box.width * 0.5, box.y + box.height * 0.3)
  const red = pval(effect(await clipOf(page, b.clips.video), 'jb.color.curves'), 'red')
  expect(red.split(' ')).toHaveLength(3)
  await page.locator('.sub-tabs button', { hasText: 'Color Wheels' }).click()
  const wheel = page.locator('[data-wheel="shadows"] .wheel')
  const wb = (await wheel.boundingBox())!
  await page.mouse.move(wb.x + wb.width / 2, wb.y + wb.height / 2)
  await page.mouse.down()
  await page.mouse.move(wb.x + wb.width * 0.9, wb.y + wb.height / 2, { steps: 3 })
  await page.mouse.up()
  const e = effect(await clipOf(page, b.clips.video), 'jb.color.wheels')
  expect(pval(e, 'shadows_x')).toBeGreaterThan(50)
})

test('titles: text, font, size, style, alignment, color, stroke, shadow, background', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.title, 'Titles')
  const t = module(page, 'Text')
  await t.locator('textarea').fill('Hi there')
  await t.locator('textarea').blur()
  await choose(page, row(page, t, 'Font'), /^Georgia$/)
  await setRow(page, t, 'Size', 12)
  await t.locator('button[title="Bold"]').click()
  await t.locator('button[title="Align left"]').click()
  await t.locator('input[type=color]').fill('#ff0000')
  await setRow(page, t, 'Letter Spacing', 0.5)
  await setModule(page, 'Stroke', true)
  await setModule(page, 'Shadow', true)
  await setModule(page, 'Background', true)
  const src = (await clipOf(page, b.clips.title)).source
  expect(src).toMatchObject({ text: 'Hi there', font_family: 'Georgia', bold: true, alignment: 'left', letter_spacing: 0.5 })
  expect(src.font_size).toBeCloseTo(0.12)
  expect(src.color.slice(0, 3)).toEqual([1, 0, 0])
  expect(src.stroke).toBeTruthy()
  expect(src.shadow).toBeTruthy()
  expect(src.background).toBeTruthy()
  await page.locator('.prop-footer button', { hasText: 'Reset' }).click()
  const reset = (await clipOf(page, b.clips.title)).source
  expect([reset.bold, reset.stroke, reset.shadow, reset.background]).toEqual([false, undefined, undefined, undefined])
})
