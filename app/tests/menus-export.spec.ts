import { type Page } from '@playwright/test'
import { expect, test, boot, choose, clipOf, effect, menuItem, project, row, seek, selectClip, state } from './helpers'

const S = 10_000_000

async function menu(page: Page, bar: string, item: string | RegExp) {
  await page.locator('.menubar button', { hasText: new RegExp(`^${bar}$`) }).dispatchEvent('mousedown')
  await menuItem(page, item)
}

test('File menu: new, save, open, export', async ({ page }) => {
  await boot(page)
  await page.evaluate(() => (window as any).__jbMock.queuePick(['/tmp/jb-ui-menu.jbp']))
  await menu(page, 'File', 'Save Project')
  await expect(page.locator('.toast')).toContainText('Saved jb-ui-menu.jbp')
  await menu(page, 'File', 'New Project')
  expect((await project(page)).media).toHaveLength(0)
  await page.evaluate(() => (window as any).__jbMock.queuePick(['/tmp/jb-ui-menu.jbp']))
  await menu(page, 'File', 'Open Project...')
  expect((await project(page)).media).toHaveLength(4)
  await menu(page, 'File', 'Export...')
  await expect(page.locator('.export-modal')).toHaveCount(1)
})

test('Edit menu: undo/redo, copy/paste, delete, split, marker', async ({ page }) => {
  const b = await boot(page)
  await selectClip(page, b.clips.audio)
  await menu(page, 'Edit', 'Copy')
  await seek(page, 5)
  await menu(page, 'Edit', 'Paste')
  expect((await project(page)).sequences[0].tracks[2].clips).toHaveLength(2)
  await menu(page, 'Edit', 'Undo')
  expect((await project(page)).sequences[0].tracks[2].clips).toHaveLength(1)
  await menu(page, 'Edit', 'Redo')
  expect((await project(page)).sequences[0].tracks[2].clips).toHaveLength(2)
  await seek(page, 1)
  await selectClip(page, b.clips.video)
  await menu(page, 'Edit', /^Split/)
  expect((await project(page)).sequences[0].tracks[0].clips).toHaveLength(3)
  await menu(page, 'Edit', 'Add Marker')
  expect((await project(page)).sequences[0].markers).toHaveLength(1)
  await menu(page, 'Edit', 'Select All')
  expect((await state(page)).selection.length).toBeGreaterThan(3)
})

test('Tools menu: tracks, snapping, freeze frame, mute, stabilization, chroma key', async ({ page }) => {
  const b = await boot(page)
  await menu(page, 'Tools', 'Add Audio Track')
  expect((await project(page)).sequences[0].tracks.filter((t: any) => t.kind === 'audio')).toHaveLength(2)
  await menu(page, 'Tools', 'Snapping')
  expect((await state(page)).snapping).toBe(false)
  await selectClip(page, b.clips.audio)
  await menu(page, 'Tools', /^Mute$/)
  expect((await clipOf(page, b.clips.audio)).audio.muted).toBe(true)
  await seek(page, 2)
  await selectClip(page, b.clips.video)
  await menu(page, 'Tools', 'Freeze Frame')
  expect((await clipOf(page, b.clips.video)).end).toBe(9 * S)
  await menu(page, 'Tools', 'Chroma Key')
  expect(effect(await clipOf(page, b.clips.video), 'jb.chroma_key')).toBeTruthy()
  await menu(page, 'Tools', 'Stabilization')
  await expect.poll(async () => effect(await clipOf(page, b.clips.video), 'jb.stabilize')?.params?.data?.value?.value ?? '').toContain('|')
})

test('View menu and keyboard: zoom, frames, marks, full screen, statistics', async ({ page }) => {
  await boot(page)
  const z = (await state(page)).zoom
  await menu(page, 'View', 'Zoom In')
  expect((await state(page)).zoom).toBeCloseTo(z * 1.5)
  await menu(page, 'View', 'Next Frame')
  await menu(page, 'View', 'Mark In')
  await menu(page, 'View', 'Next Frame')
  await menu(page, 'View', 'Mark Out')
  const st = await state(page)
  expect([st.markIn, st.markOut]).toEqual([Math.ceil(S / 30), Math.ceil((2 * S) / 30)])
  await menu(page, 'View', 'Clear In/Out')
  expect((await state(page)).markIn).toBeNull()
  await menu(page, 'View', 'Full Screen Preview')
  expect((await state(page)).playerFullscreen).toBe(true)
  await page.keyboard.press('Escape')
  await menu(page, 'View', 'Show Playback Statistics')
  expect((await state(page)).showStats).toBe(true)
  await page.locator('body').click({ position: { x: 5, y: 900 } })
  await page.keyboard.press('i')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('o')
  expect((await state(page)).markOut).toBe(Math.ceil((3 * S) / 30))
})

test('Help menu opens the project pages; title bar buttons', async ({ page }) => {
  await boot(page)
  await menu(page, 'Help', 'Report an Issue')
  await menu(page, 'Help', 'Jibaru Editor on GitHub')
  await menu(page, 'Help', 'Keyboard Shortcuts')
  await expect(page.locator('.toast')).toContainText('J/K/L')
  // The updater only exists in the desktop app; the browser build says so.
  await menu(page, 'Help', 'Check for Updates...')
  await expect(page.locator('.update-notice')).toContainText('desktop app')
  await page.locator('.update-notice button', { hasText: 'Close' }).click()
  await expect(page.locator('.update-notice')).toHaveCount(0)
  await menu(page, 'Help', 'Check for Updates Automatically')
  expect(await page.evaluate(() => localStorage.getItem('jb.updates.auto'))).toBe('off')
  await page.locator('.title-actions button[title="Feedback"]').click()
  await page.locator('.title-actions button[title="What\'s new"]').click()
  await page.locator('.title-actions button[title="Help and documentation"]').click()
  const opened = await page.evaluate(() => (window as any).__jbOpened)
  expect(opened).toEqual([
    'https://github.com/Jibaru/jibaru-editor/issues',
    'https://github.com/Jibaru/jibaru-editor',
    'https://github.com/Jibaru/jibaru-editor/issues/new',
    'https://github.com/Jibaru/jibaru-editor/releases',
    'https://github.com/Jibaru/jibaru-editor#readme',
  ])
  await expect(page.locator('.title-actions button[title^="Cloud backup"]')).toBeDisabled()
  await expect(page.locator('.title-actions button[title^="Share"]')).toBeDisabled()
  await page.locator('.title-actions button[title="Layout"]').click()
  await menuItem(page, 'Larger Player')
  expect((await state(page)).layout.libW).toBe(400)
  await page.locator('.title-actions button[title="More"]').click()
  await menuItem(page, 'About Jibaru Editor')
  await expect(page.locator('.toast')).toContainText(/Jibaru Editor \d+\.\d+\.\d+/)
  await page.evaluate(() => (window as any).__jbMock.queuePick(['/tmp/jb-ui-titlebar.jbp']))
  await page.locator('.title-actions button[title^="Save"]').click()
  await expect(page.locator('.toast')).toContainText('Saved jb-ui-titlebar.jbp')
})

