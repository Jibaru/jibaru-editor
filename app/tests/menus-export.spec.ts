test('export dialog: every option', async ({ page }) => {
  await boot(page)
  await seek(page, 1)
  await page.keyboard.press('i')
  await page.locator('.titlebar .export-btn').click()
  const f = page.locator('.export-form')
  await row(page, f, 'Name').locator('input').fill('My Cut')
  await row(page, f, 'Save to').locator('input').fill('/tmp/out')
  await choose(page, row(page, f, 'Format'), 'MOV')
  await choose(page, row(page, f, 'Encoder'), /HEVC/)
  await choose(page, row(page, f, 'Resolution'), /1280 x 720/)
  await choose(page, row(page, f, 'Frame Rate'), /^24 fps$/)
  await row(page, f, 'Quality').locator('button', { hasText: 'Higher' }).click()
  await row(page, f, 'Range').locator('button', { hasText: 'In/Out marks' }).click()
  await expect(f.locator('.export-summary')).toContainText('00:00:06:00')
  await row(page, f, 'Range').locator('button', { hasText: 'Custom' }).click()
  await f.locator('.tc-field').first().fill('00:00:02:00')
  await f.locator('.tc-field').last().fill('00:00:04:00')
  await expect(f.locator('.export-summary')).toContainText('00:00:02:00')
  await row(page, f, 'Audio').locator('.switch').click()
  await row(page, f, 'Hardware Encoding').locator('.switch').click()
  await expect(page.locator('.export-modal footer .export-path')).toHaveText('/tmp/out/My Cut.mov')
  await expect(page.locator('.export-targets button', { hasText: 'Social' })).toBeDisabled()
  await page.locator('.export-modal header button').click()
  await expect(page.locator('.export-modal')).toHaveCount(0)
})
